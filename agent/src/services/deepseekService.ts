/**
 * DeepSeek LLM Service — Text Intelligence Parsing & Reasoning Analysis
 *
 * Two capabilities:
 *   1. parseTextIntelligence — converts free-form market text into structured intel
 *   2. analyzeReasoning — scores the quality/strength of agent reasoning (0.0–1.0)
 *
 * Requires: DEEPSEEK_API_KEY in env
 */

import axios from 'axios';

const DEEPSEEK_API_URL = 'https://api.deepseek.com/v1/chat/completions';
const DEEPSEEK_MODEL = 'deepseek-chat';
const TIMEOUT_MS = 15_000;

function getApiKey(): string | null {
  return process.env.DEEPSEEK_API_KEY || null;
}

// ── Response types ────────────────────────────────────────────────────────────

export interface ParsedTextIntelligence {
  direction: 'BULLISH' | 'BEARISH' | 'NEUTRAL';
  confidence: number;       // 0–100
  reasoning: string;        // concise summary generated by LLM
  keyFactors: string[];     // specific market drivers extracted
}

export interface ReasoningAnalysis {
  reasoningStrength: number;  // 0.0–1.0
  factors: string[];          // specific factors mentioned in reasoning
}

// ── Internal helper ───────────────────────────────────────────────────────────

async function callDeepSeek(systemPrompt: string, userPrompt: string): Promise<string> {
  const apiKey = getApiKey();
  if (!apiKey) throw new Error('DEEPSEEK_API_KEY not configured');

  const resp = await axios.post(
    DEEPSEEK_API_URL,
    {
      model: DEEPSEEK_MODEL,
      messages: [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: userPrompt },
      ],
      temperature: 0.1,
      max_tokens: 400,
    },
    {
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json',
      },
      timeout: TIMEOUT_MS,
    },
  );

  return resp.data?.choices?.[0]?.message?.content || '';
}

function extractJson(text: string): any {
  const match = text.match(/\{[\s\S]*\}/);
  if (!match) throw new Error('No JSON object found in LLM response');
  return JSON.parse(match[0]);
}

// ── Public API ────────────────────────────────────────────────────────────────

/**
 * Parse free-form market text into structured intelligence.
 * Used when an agent POSTs { symbol, text } without structured fields.
 *
 * Example input: "BTC要涨因为美联储降息预期推动市场走高"
 * Example output: { direction: 'BULLISH', confidence: 72, reasoning: '...', keyFactors: ['Fed rate cut', ...] }
 */
export async function parseTextIntelligence(
  text: string,
  symbol: string,
): Promise<ParsedTextIntelligence> {
  const systemPrompt =
    'You are a financial market analyst. Parse market intelligence and return structured JSON only. No explanation outside JSON.';

  const userPrompt = `Symbol: ${symbol}
Text: "${text}"

Extract structured intelligence. Return ONLY valid JSON:
{
  "direction": "BULLISH" | "BEARISH" | "NEUTRAL",
  "confidence": <integer 0-100>,
  "reasoning": "<concise English summary of the view>",
  "keyFactors": ["<specific market factor>", ...]
}

Rules:
- confidence: 50=uncertain, 70=moderately confident, 90=highly confident
- keyFactors: list only concrete market drivers mentioned (max 5)
- direction based purely on market analysis, not tone`;

  const content = await callDeepSeek(systemPrompt, userPrompt);
  const parsed = extractJson(content);

  const validDirections = ['BULLISH', 'BEARISH', 'NEUTRAL'];
  return {
    direction: validDirections.includes(parsed.direction) ? parsed.direction : 'NEUTRAL',
    confidence: Math.max(0, Math.min(100, Math.round(Number(parsed.confidence) || 50))),
    reasoning: String(parsed.reasoning || '').slice(0, 500),
    keyFactors: Array.isArray(parsed.keyFactors)
      ? parsed.keyFactors.slice(0, 5).map(String)
      : [],
  };
}

/**
 * Analyze the quality and specificity of an agent's reasoning string.
 * Returns a 0.0–1.0 score and extracted specific factors.
 *
 * Score scale:
 *   0.0 — Empty or irrelevant text
 *   0.2 — Vague/emotional ("looks bullish", "feeling good about it")
 *   0.5 — General market reference ("trend is up", "volume increasing")
 *   0.7 — Specific indicators ("RSI oversold at 28", "EMA crossover")
 *   1.0 — Comprehensive analysis with multiple data points
 */
export async function analyzeReasoning(
  reasoning: string,
  direction: string,
  symbol: string,
): Promise<ReasoningAnalysis> {
  if (!reasoning || reasoning.trim().length < 8) {
    return { reasoningStrength: 0, factors: [] };
  }

  const systemPrompt =
    'You evaluate trading signal reasoning quality. Return JSON only. No explanation outside JSON.';

  const userPrompt = `Symbol: ${symbol}
Declared direction: ${direction}
Agent reasoning: "${reasoning}"

Score the reasoning quality from 0.0 to 1.0:
- 0.0: empty, gibberish, or no market content
- 0.2: vague emotion ("looks bullish", "I think it will go up")
- 0.4: general market statement without data ("trend looks up", "volume is high")
- 0.7: specific indicator reference ("RSI=28 oversold", "EMA20 crossed above EMA50")
- 1.0: comprehensive data-backed analysis (multiple indicators, price levels, timeframe)

Return ONLY valid JSON:
{
  "reasoningStrength": <float 0.0-1.0>,
  "factors": ["<specific factor or indicator mentioned>", ...]
}`;

  try {
    const content = await callDeepSeek(systemPrompt, userPrompt);
    const parsed = extractJson(content);

    return {
      reasoningStrength: Math.max(0, Math.min(1, Number(parsed.reasoningStrength) || 0)),
      factors: Array.isArray(parsed.factors) ? parsed.factors.slice(0, 5).map(String) : [],
    };
  } catch {
    // Fallback: simple length-based heuristic if LLM fails
    const len = reasoning.trim().length;
    return {
      reasoningStrength: len > 100 ? 0.4 : len > 30 ? 0.2 : 0.1,
      factors: [],
    };
  }
}

/** Check if DeepSeek is available (key configured) */
export function isDeepSeekAvailable(): boolean {
  return !!getApiKey();
}
